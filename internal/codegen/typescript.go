package codegen

import (
	"fmt"
	"strings"
)

// EmitTypeScript generates a TypeScript typed-invoker file from a
// CodegenResult.
//
// The output is an interface named <InterfaceName>Invoker plus a factory
// `create<InterfaceName>Invoker(base, iface?)` that binds the runtime OBI
// once at construction. Each operation becomes one method returning the
// typed, cardinality-agnostic `Invocation<I, O>` handle — never a
// Promise-returning unary wrapper and never a *Stream twin. The caller
// decides cardinality through usage of the handle; the signature does not
// declare it.
func EmitTypeScript(r *CodegenResult) string {
	var b strings.Builder

	invokerName := fmt.Sprintf("%sInvoker", r.InterfaceName)

	// --- Imports ---
	b.WriteString("// Auto-generated by ob codegen — do not edit\n")
	b.WriteString(fmt.Sprintf("// Requires %s (the Invocation handle API).\n", TSSDKRange))
	b.WriteString("import {\n")
	b.WriteString("  type OperationInvoker,\n")
	b.WriteString("  type OBInterface,\n")
	b.WriteString("  type Invocation,\n")
	b.WriteString("} from \"@openbindings/sdk\";\n\n")

	// --- Types ---
	if len(r.Types) > 0 {
		b.WriteString("// --- Types ---\n\n")
		for _, td := range r.Types {
			emitTSInterface(&b, td)
		}
	}

	// --- Per-call options ---
	b.WriteString("// --- Call options ---\n\n")
	b.WriteString("/** Optional per-call arguments accepted by every generated method. */\n")
	b.WriteString("export interface InvokerCallOpts {\n")
	b.WriteString("  /** Per-call invocation context (credentials, configuration). */\n")
	b.WriteString("  context?: Record<string, unknown>;\n")
	b.WriteString("  /** Pin a specific binding instead of the default selection. */\n")
	b.WriteString("  bindingKey?: string;\n")
	b.WriteString("  /** External cancellation; converges with the handle's cancel(). */\n")
	b.WriteString("  signal?: AbortSignal;\n")
	b.WriteString("}\n\n")

	// --- Embedded contract ---
	b.WriteString("// --- Embedded contract ---\n\n")
	b.WriteString("const INTERFACE: OBInterface = JSON.parse('")
	b.WriteString(tsEscapeSingleQuoteString(string(r.RawOBI)))
	b.WriteString("');\n\n")
	b.WriteString(fmt.Sprintf("/** The OBI contract %s was generated against. Operations + schemas only; no bindings. */\n", invokerName))
	b.WriteString("export const CONTRACT: OBInterface = INTERFACE;\n\n")

	// --- Typed invoker interface ---
	b.WriteString("// --- Invoker ---\n\n")
	var doc strings.Builder
	if r.Description != "" {
		doc.WriteString(r.Description)
		doc.WriteString("\n\n")
	}
	doc.WriteString(fmt.Sprintf("%s exposes typed methods for the operations declared by the", invokerName))
	doc.WriteString("\ncodegen-time OBI contract. Each method returns the cardinality-agnostic")
	doc.WriteString("\ninvocation handle: write inputs until done, iterate outputs until done —")
	doc.WriteString("\none shape for unary, streaming, and bidirectional bindings. For an")
	doc.WriteString("\noperation you are confident yields exactly one output, use the SDK's")
	doc.WriteString("\n`single(call.outputs)` terminal.")
	b.WriteString(tsDocComment(doc.String(), ""))

	b.WriteString(fmt.Sprintf("export interface %s {\n", invokerName))
	for _, op := range r.Operations {
		emitTSMethodSignature(&b, op)
	}
	b.WriteString("}\n\n")

	// --- Factory ---
	b.WriteString(fmt.Sprintf("/**\n * Wraps an OperationInvoker with typed methods, binding the runtime\n * interface once at construction. Defaults to the embedded codegen-time\n * contract; to target several providers of the same contract, create one\n * typed invoker per provider.\n */\n"))
	b.WriteString(fmt.Sprintf("export function create%s(\n", invokerName))
	b.WriteString("  base: OperationInvoker,\n")
	b.WriteString("  iface: OBInterface = INTERFACE,\n")
	b.WriteString(fmt.Sprintf("): %s {\n", invokerName))
	b.WriteString("  return {\n")
	for _, op := range r.Operations {
		emitTSMethodImpl(&b, op)
	}
	b.WriteString("  };\n")
	b.WriteString("}\n")

	return b.String()
}

// tsIOTypes returns the I/O type parameters for an operation's handle. An
// operation with no declared input gets `never` (the binding closes the
// input side itself; the caller cannot write); an undeclared output is
// `unknown`.
func tsIOTypes(op OperationSig) (inputType, outputType string) {
	inputType = "never"
	if op.Input != nil {
		inputType = tsTypeRef(*op.Input)
	}
	outputType = "unknown"
	if op.Output != nil {
		outputType = tsTypeRef(*op.Output)
	}
	return inputType, outputType
}

func emitTSMethodSignature(b *strings.Builder, op OperationSig) {
	methodName := toCamelCase(op.Key)
	inputType, outputType := tsIOTypes(op)

	if op.Description != "" || op.Deprecated {
		b.WriteString("  /**\n")
		if op.Deprecated {
			b.WriteString("   * @deprecated\n")
		}
		if op.Description != "" {
			b.WriteString(fmt.Sprintf("   * %s\n", op.Description))
		}
		b.WriteString("   */\n")
	}
	b.WriteString(fmt.Sprintf("  %s(opts?: InvokerCallOpts): Invocation<%s, %s>;\n",
		methodName, inputType, outputType))
}

func emitTSMethodImpl(b *strings.Builder, op OperationSig) {
	methodName := toCamelCase(op.Key)
	inputType, outputType := tsIOTypes(op)

	b.WriteString(fmt.Sprintf("    %s: (opts) =>\n", methodName))
	b.WriteString(fmt.Sprintf("      base.invoke<%s, %s>({\n", inputType, outputType))
	b.WriteString("        interface: iface,\n")
	b.WriteString(fmt.Sprintf("        operation: \"%s\",\n", op.Key))
	b.WriteString("        context: opts?.context,\n")
	b.WriteString("        bindingKey: opts?.bindingKey,\n")
	b.WriteString("        signal: opts?.signal,\n")
	b.WriteString("      }),\n")
}

func emitTSInterface(b *strings.Builder, td TypeDef) {
	if td.Description != "" {
		b.WriteString(tsDocComment(td.Description, ""))
	}
	b.WriteString(fmt.Sprintf("export interface %s {\n", td.Name))
	for _, f := range td.Fields {
		if f.Description != "" {
			b.WriteString(tsDocComment(f.Description, "  "))
		}
		opt := ""
		if !f.Required {
			opt = "?"
		}
		b.WriteString(fmt.Sprintf("  %s%s: %s;\n", f.JSONName, opt, tsTypeRef(f.Type)))
	}
	b.WriteString("}\n\n")
}

// tsTypeRef converts an IR TypeRef to a TypeScript type string.
func tsTypeRef(ref TypeRef) string {
	var base string
	switch ref.Kind {
	case KindPrimitive:
		if ref.Enum != nil {
			return tsEnumType(ref.Enum, ref.Nullable)
		}
		if ref.Const != nil {
			return tsConstType(ref.Const, ref.Nullable)
		}
		switch ref.Primitive {
		case "string":
			base = "string"
		case "number", "integer":
			base = "number"
		case "boolean":
			base = "boolean"
		default:
			base = "unknown"
		}
	case KindNamed:
		base = ref.Name
	case KindArray:
		if ref.Items != nil {
			itemType := tsTypeRef(*ref.Items)
			// Wrap the item type in parentheses whenever it renders as a
			// TypeScript union, otherwise `T[]` precedence binds the `[]`
			// to only the LAST variant of the union.
			if strings.Contains(itemType, " | ") {
				base = fmt.Sprintf("(%s)[]", itemType)
			} else {
				base = fmt.Sprintf("%s[]", itemType)
			}
		} else {
			base = "unknown[]"
		}
	case KindMap:
		valType := "unknown"
		if ref.Values != nil {
			valType = tsTypeRef(*ref.Values)
		}
		base = fmt.Sprintf("Record<string, %s>", valType)
	case KindUnion:
		parts := make([]string, len(ref.Variants))
		for i, v := range ref.Variants {
			parts[i] = tsTypeRef(v)
		}
		base = strings.Join(parts, " | ")
	default:
		base = "unknown"
	}

	if ref.Nullable && ref.Kind != KindUnion {
		return base + " | null"
	}
	return base
}

func tsEnumType(values []any, nullable bool) string {
	parts := make([]string, len(values))
	for i, v := range values {
		switch val := v.(type) {
		case string:
			parts[i] = fmt.Sprintf("%q", val)
		case float64:
			if val == float64(int64(val)) {
				parts[i] = fmt.Sprintf("%d", int64(val))
			} else {
				parts[i] = fmt.Sprintf("%g", val)
			}
		default:
			parts[i] = fmt.Sprintf("%v", val)
		}
	}
	result := strings.Join(parts, " | ")
	if nullable {
		result += " | null"
	}
	return result
}

func tsConstType(val any, nullable bool) string {
	var s string
	switch v := val.(type) {
	case string:
		s = fmt.Sprintf("%q", v)
	case float64:
		if v == float64(int64(v)) {
			s = fmt.Sprintf("%d", int64(v))
		} else {
			s = fmt.Sprintf("%g", v)
		}
	case bool:
		s = fmt.Sprintf("%t", v)
	default:
		s = fmt.Sprintf("%v", v)
	}
	if nullable {
		return s + " | null"
	}
	return s
}

func tsDocComment(text, indent string) string {
	lines := strings.Split(text, "\n")
	if len(lines) == 1 {
		return fmt.Sprintf("%s/** %s */\n", indent, text)
	}
	var b strings.Builder
	b.WriteString(fmt.Sprintf("%s/**\n", indent))
	for _, line := range lines {
		b.WriteString(fmt.Sprintf("%s * %s\n", indent, line))
	}
	b.WriteString(fmt.Sprintf("%s */\n", indent))
	return b.String()
}

func tsEscapeSingleQuoteString(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "'", "\\'")
	return s
}
